      "Treg-T 'suppressed expansion' in ER-negative/basal and BRCA1 (Danenberg 2022)",
      "Tumour-Treg co-localisation higher in node-positive disease (Zhang 2022, HNSCC)"),
    `This analysis` = c(
      sprintf("immune fraction Basal %s (METABRIC), TN %s (Basel)", sgn(pe("pam50Basal")), sgn(p1[term == "surrogateTN", estimate])),
      sprintf("%s with CELESTA labels (p %s); %s with published labels", sgn(pe("pam50Her2")), fp(p1[term == "pam50Her2" & labels == "CELESTA", p]),
              sgn(pe("pam50Her2", "published"))),
      sprintf("median Tumour -> T and Tumour -> Macrophage CLQ %s across subtypes and cohorts",
              rng(desc[cell_A == "Tumour" & cell_B %in% c("T cell", "Macrophage"), median])),
      sprintf("median T -> Endothelial CLQ %s", rng(desc[cell_A == "T cell" & cell_B == "Endothelial", median])),
      sprintf("Basal - LumA: Tumour -> Tumour %s, Stroma -> Stroma %s (both CIs include 0)",
              sgn(p2e("P2a", "Tumour", "Tumour")), sgn(p2e("P2a", "Stroma", "Stroma"))),
      sprintf("Basal - LumA: B -> T %s, T -> B %s (both CIs include 0)", sgn(p2e("P2b", "B cell", "T cell")), sgn(p2e("P2b", "T cell", "B cell"))),
      sprintf("Basal - LumA: Treg -> CD8 T %s, Treg -> CD4 T %s; BRCA1-mutant patients with a defined pair: %s",
              sgn(p2e("P2c", "Treg", "CD8 T cell")), sgn(p2e("P2c", "Treg", "CD4 T cell")),
              if (brca_n[1] == brca_n[2]) brca_n[1] else paste(brca_n, collapse = "-")),
      sprintf("CELESTA labels %s (p %s); published labels %s (p %s, n = %d)",
              sgn(qd[labels == "CELESTA" & adjusted == TRUE & cell_A == "Tumour" & cell_B == "Treg", estimate]),
              fp(qd[labels == "CELESTA" & adjusted == TRUE & cell_A == "Tumour" & cell_B == "Treg", p]),
              sgn(qd_pub$estimate), fp(qd_pub$p), qd_pub$n)),
    Verdict = c("agrees", "partly agrees (depends on the cell typing)", "agrees", "agrees", "not reproduced",
                "not reproduced (same direction only)", "not reproduced / BRCA1 not testable",
                "not reproduced; no earlier breast-cancer test found"))
  lines <- c(lines, "## Comparison with prior work", "", md(cmp))
  writeLines(lines, file.path(gen, if (DRY) "tables_dryrun.md" else "tables.md"))

  # ================================================================== figures
  # 1. subtype x pair heatmap (k = 20): mean patient CLQ per subtype (log2), marks for Q1 discoveries
  feat <- fread(file.path(gen, "features", "metabric_celesta_clq.csv.gz"), colClasses = list(character = "PID"))
  pats <- fread(file.path(gen, "patients_metabric.csv"), colClasses = list(character = "PID"), na.strings = c("", "NA"))
  if (DRY) { set.seed(1); pats[, pam50 := pam50[sample(.N)]] }
  hm <- merge(feat[k == 20], pats[!is.na(pam50), .(PID, pam50)], by = "PID")[
    , .(mean_clq = mean(clq_k)), by = .(cell_A, cell_B, pam50)]
  hm <- merge(hm, q1[adjusted == TRUE & k == 20, .(cell_A, cell_B, q)], by = c("cell_A", "cell_B"), all.x = TRUE)
  cc <- q1c[adjusted == TRUE & k == 20, .(cell_A, cell_B, pam50 = sub(" - LumA", "", contrast), p_contrast = p)]
  hm <- merge(hm, cc, by = c("cell_A", "cell_B", "pam50"), all.x = TRUE)
  hm[, pair := paste0(cell_A, " -> ", cell_B, ifelse(!is.na(q) & q < 0.05, "  *", ""))]
  hm[, pam50 := factor(pam50, PAM50_LEVELS)]
  hm[, mark := ifelse(!is.na(q) & q < 0.05 & !is.na(p_contrast) & p_contrast < 0.05, "•", "")]
  ord <- hm[pam50 == "LumA"][order(cell_A, cell_B), pair]
  hm[, pair := factor(pair, rev(unique(ord)))]
  g <- ggplot(hm, aes(pam50, pair, fill = log2(mean_clq))) + geom_tile(colour = "white") +
    geom_text(aes(label = mark), size = 3) +
    scale_fill_gradient2(low = "#2166ac", mid = "#f7f7f7", high = "#b2182b", midpoint = 0, name = "log2 mean CLQ") +
    labs(x = NULL, y = "centre -> neighbour", title = "METABRIC: CLQ by PAM50 subtype (k = 20, CELESTA classes)",
         subtitle = paste0("* subtype F-test q < 0.05 (adjusted for CLR composition, log cells, age, grade)
",
                    "• that subtype differs from LumA at p < 0.05 (marked only on * pairs)")) +
    theme(axis.text.y = element_text(size = 6), panel.grid = element_blank())
  ggsave(file.path(fig, paste0("genotype_heatmap", sfx, ".png")), g, width = 7.5, height = 12, dpi = 150)

  # 2. forest plots for H1-H3
  h1 <- q1c[cell_A %in% c("Tumour", "CD8 T cell") & cell_B %in% c("Tumour", "CD8 T cell") & cell_A != cell_B &
              contrast == "Basal - LumA"][, panel := "H1: Basal - LumA"]
  h1[, label := sprintf("%s -> %s, k = %d, %s", cell_A, cell_B, k, ifelse(adjusted, "adjusted", "unadjusted"))]
  h2all <- q2t[cell_A == "Tumour" & cell_B == "Macrophage"][, panel := "Q2 (all subtypes): TP53 mut - wt"]
  h2all[, label := sprintf("Tumour -> Macrophage, k = %d, %s", k, ifelse(adjusted, "adjusted", "unadjusted"))]
  ho_h2 <- ho[id == "H2"][, .(estimate, lo, hi, panel = "H2: ER+ only, TP53 mut - wt", label = "Tumour -> Macrophage, k = 20, adjusted (pre-registered)")]
  rows <- rbind(h1[, .(estimate, lo, hi, panel, label)], ho_h2, h2all[, .(estimate, lo, hi, panel, label)])
  if (nrow(rep)) {
    rows <- rbind(rows,
                  rep[, .(estimate = metabric_estimate, lo = metabric_lo, hi = metabric_hi, panel = "H3: replicated contrasts",
                          label = sprintf("METABRIC %s, %s -> %s, k = %d", metabric_contrast, cell_A, cell_B, k))],
                  rep[, .(estimate = basel_estimate, lo = basel_lo, hi = basel_hi, panel = "H3: replicated contrasts",
                          label = sprintf("Basel %s, %s -> %s, k = %d", basel_contrast, cell_A, cell_B, k))])
  }
  rows[, label := factor(label, rev(unique(label)))]
  g <- ggplot(rows, aes(estimate, label)) + geom_vline(xintercept = 0, colour = "grey60") +
    geom_errorbar(aes(xmin = lo, xmax = hi), width = 0.25, orientation = "y", colour = "#3b5b92") + geom_point(colour = "#3b5b92") +
    facet_grid(panel ~ ., scales = "free_y", space = "free_y") +
    labs(x = "difference in CLQ (95% CI)", y = NULL, title = "Pre-registered hypotheses: effect sizes") +
    theme(strip.text.y = element_text(angle = 0, hjust = 0), axis.text.y = element_text(size = 7))
  ggsave(file.path(fig, paste0("genotype_forest", sfx, ".png")), g, width = 10, height = max(4, 0.22 * nrow(rows) + 2), dpi = 150)

  # 3. replication scatter: every METABRIC round-1 contrast vs its Basel counterpart
  ar <- fread(file.path(mod, "replication_all_contrasts.csv"))
  ar[, status := ifelse(metabric_q < 0.05, "METABRIC q < 0.05", "not significant in METABRIC")]
  lim <- range(c(ar$metabric_estimate, ar$basel_estimate), na.rm = TRUE)
  g <- ggplot(ar, aes(metabric_estimate, basel_estimate, colour = status, shape = contrast)) +
    geom_hline(yintercept = 0, colour = "grey70") + geom_vline(xintercept = 0, colour = "grey70") +
    geom_abline(slope = 1, intercept = 0, linetype = 2, colour = "grey60") + geom_point(alpha = 0.8) +
    facet_wrap(~k, labeller = label_both) + coord_equal(xlim = lim, ylim = lim) +
    scale_colour_manual(values = c("METABRIC q < 0.05" = "#b2182b", "not significant in METABRIC" = "grey60")) +
    labs(x = "METABRIC (PAM50 Basal or Her2 vs LumA)", y = "Basel (TN or HER2+ vs ER+/HER2-)", colour = NULL, shape = NULL,
         title = "Replication: adjusted subtype contrasts in CLQ, METABRIC vs Basel (shared round-1 classes)") +
    theme(legend.position = "bottom")
  ggsave(file.path(fig, paste0("genotype_replication", sfx, ".png")), g, width = 10, height = 4.8, dpi = 150)

  # 4. example cores per subtype, coloured by CELESTA class (image closest to the subtype's median composition)
  if (!DRY) {
    lab <- fread(file.path(gen, "cell_labels_metabric.csv.gz"), select = c("cell_id", "image", "celesta_type"))
    cells <- fread(file.path(root, "data", "processed", "genotype", "metabric_cells.csv.gz"),
                   select = c("cell_id", "image", "PID", "X", "Y"))
    d <- merge(cells, lab, by = c("cell_id", "image"))
    d <- merge(d, pats[!is.na(pam50), .(PID, pam50)], by = "PID")
    comp <- d[, .N, by = .(image, pam50, celesta_type)][, f := N / sum(N), by = image]
    w <- dcast(comp, image + pam50 ~ celesta_type, value.var = "f", fill = 0)
    cls <- setdiff(names(w), c("image", "pam50"))
    nimg <- d[, .N, by = image]
    w <- merge(w, nimg, by = "image")[N >= 1000]
    pick <- w[, {
      med <- sapply(.SD, median)
      dist <- rowSums((as.matrix(.SD) - matrix(med, .N, length(med), byrow = TRUE))^2)
      .(image = image[which.min(dist)])
    }, by = pam50, .SDcols = cls]
    ex <- merge(d, pick, by = c("image", "pam50"))
    ex[, pam50 := factor(pam50, PAM50_LEVELS)]
    ex[, panel := factor(paste0(pam50, " (", image, ")"))]; ex[, panel := factor(panel, unique(panel[order(pam50)]))]
    ex[, celesta_type := factor(celesta_type, names(CLASS_COLOURS))]
    g <- ggplot(ex, aes(X, Y, colour = celesta_type)) + geom_point(size = 0.35) +
      facet_wrap(~panel, nrow = 1) + coord_equal() + scale_y_reverse() +
      scale_colour_manual(values = CLASS_COLOURS, drop = FALSE, name = NULL) +
      guides(colour = guide_legend(override.aes = list(size = 3), nrow = 2)) +
      labs(x = NULL, y = NULL, title = "Example METABRIC cores per PAM50 subtype (core closest to the subtype's median composition), official CELESTA labels") +
