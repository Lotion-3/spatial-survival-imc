                                                 panel.grid.minor = element_blank()))

f3 <- function(x) formatC(x, format = "f", digits = 3)
f2 <- function(x) formatC(x, format = "f", digits = 2)
fp <- function(p) ifelse(is.na(p), "–", ifelse(p < 0.001, formatC(p, format = "e", digits = 1), formatC(p, format = "f", digits = 3)))
ci <- function(e, lo, hi) sprintf("%s [%s, %s]", f3(e), f3(lo), f3(hi))
md <- function(dt) {
  h <- paste0("| ", paste(names(dt), collapse = " | "), " |")
  s <- paste0("|", paste(rep("---", ncol(dt)), collapse = "|"), "|")
  r <- apply(dt, 1, function(x) paste0("| ", paste(x, collapse = " | "), " |"))
  c(h, s, r, "")
}

main <- function() {
  lines <- c("# Part IV tables (generated by scripts/genotype_report.R from results/genotype/)", "")

  # ---- stage 0/1 tables
  counts <- fromJSON(file.path(gen, "cohort_counts.json"))
  share <- fread(file.path(gen, "celesta", "class_share.csv"))
  acc <- fread(file.path(gen, "celesta", "acceptance.csv"))
  conc <- fread(file.path(gen, "celesta", "concordance_summary.csv"))
  tsub <- fread(file.path(gen, "celesta", "concordance_tsubsets_metabric.csv"))
  lines <- c(lines, "## Cell typing (official CELESTA)", "",
             md(share[!celesta_type %in% "Skipped", .(Cohort = cohort, Class = celesta_type, Cells = format(N, big.mark = ",", trim = TRUE),
                                                      Share = sprintf("%.1f%%", 100 * share))]),
             md(acc[, .(Cohort = cohort, Class = cell_type, `Defining marker` = defining_marker,
                        `Images with marker` = images_marker_present, `Images assigned` = images_assigned,
                        Share = f3(share_assigned))]),
             md(conc[, .(Cohort = cohort, `Cells assigned to a shared class` = format(cells_celesta_assigned, big.mark = ",", trim = TRUE),
                         Agreement = f3(agreement_assigned), `Cohen's kappa` = f3(kappa_assigned))]),
             md(tsub[, .(`CELESTA class` = celesta_class, `Published class` = gsub("\\^\\{\\+\\}", "+", gsub("_\\{([A-Za-z]+)\\}", "\\1", published_phenotype)),
                         `CELESTA cells` = format(celesta_cells, big.mark = ",", trim = TRUE), `Published cells` = format(published_cells, big.mark = ",", trim = TRUE),
