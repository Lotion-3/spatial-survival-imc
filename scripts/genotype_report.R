  pp <- q2p[adjusted == TRUE][order(p)][1:min(.N, 5)]
  lines <- c(lines, md(pp[, .(Pair = paste(cell_A, "->", cell_B), k, `PIK3CA mut - wt` = ci(estimate, lo, hi), p = fp(p),
                              q = fp(q), n, `n mutant` = n_group1)]))

