  rob <- data.table(
    Check = c("Subtype-label permutation: share of 1,000 permutations with any BH discovery",
              "Subtype-label permutation: mean null p-value", "Permutation check calibrated (pre-registered rule)",
              "Q1 discoveries significant (p < 0.05) at both other k",
              "Published labels, k = 20: Spearman correlation of subtype F across pairs",
              "Published labels: Basal - LumA sign agreement (pairs defined in both)",
              "Published labels: CELESTA k = 20 discoveries with published q < 0.05",
              "Lab convention (Unknown cells kept in graph), k = 20: Spearman correlation of F",
              "Lab convention: CELESTA k = 20 discoveries also q < 0.05"),
    Value = c(f3(ps$share_perms_any_discovery), f3(ps$mean_null_p), ifelse(ps$calibrated, "yes", "no"),
              if (nrow(loko)) sprintf("%d of %d", sum(loko$consistent), nrow(loko)) else "no discoveries",
              f3(alt[, cor(F_celesta, F_published, method = "spearman", use = "complete.obs")]),
              f3(alt[!is.na(est_celesta) & !is.na(est_published), mean(sign(est_celesta) == sign(est_published))]),
              sprintf("%d of %d", alt[q_celesta < 0.05, sum(q_published < 0.05, na.rm = TRUE)], alt[, sum(q_celesta < 0.05, na.rm = TRUE)]),
              f3(unk_cmp[, cor(F1, F2, method = "spearman")]),
              sprintf("%d of %d", unk_cmp[q1 < 0.05, sum(q2 < 0.05)], unk_cmp[, sum(q1 < 0.05)])))
  lines <- c(lines, "## Robustness", "", md(rob))

  # ---- replication
  rep <- fread(file.path(mod, "replication.csv"))
  repf <- fread(file.path(mod, "replication_metabric_family.csv"))
  lines <- c(lines, "## Replication in Basel", "",
             md(data.table(`METABRIC round-1 contrasts tested` = nrow(repf), `q < 0.05` = repf[, sum(q < 0.05)],
