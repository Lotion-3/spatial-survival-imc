  ps <- fromJSON(file.path(mod, "permutation_summary.json"))
  loko <- fread(file.path(mod, "leave_one_k_out.csv"))
  alt <- fread(file.path(mod, "alt_typing_comparison.csv"))
  unk <- fread(file.path(mod, "sensitivity_keepunknown_q1_tests.csv"))
  m20 <- q1[adjusted == TRUE & k == 20]
  unk_cmp <- merge(m20[, .(cell_A, cell_B, F1 = F, q1 = q)], unk[adjusted == TRUE, .(cell_A, cell_B, F2 = F, q2 = q)],
