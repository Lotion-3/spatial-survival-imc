                           `Same sign and Basel p < 0.05` = if (nrow(rep)) rep[, sum(same_sign & basel_p < 0.05)] else 0)))
  if (nrow(rep)) lines <- c(lines, md(rep[order(metabric_q), .(Pair = paste(cell_A, "->", cell_B), k,
                                                                 METABRIC = paste(metabric_contrast, ci(metabric_estimate, metabric_lo, metabric_hi)),
                                                                 `METABRIC q` = fp(metabric_q),
                                                                 Basel = paste(basel_contrast, ci(basel_estimate, basel_lo, basel_hi)),
                                                                 `Basel p` = fp(basel_p), `Same sign` = ifelse(same_sign, "yes", "no"))]))
  desc <- fread(file.path(mod, "descriptive_keren_jackson.csv"))
  lines <- c(lines, "## Descriptive (Keren 2018, Jackson 2020)", "",
             md(desc[order(cohort, cell_A, cell_B, group), .(Cohort = cohort, Group = group, Pair = paste(cell_A, "->", cell_B), n,
                                                              Median = f3(median), IQR = f3(iqr))]))
  # ---- comparison with prior work (every number from the saved results above)
  pe <- function(tm, lab = "CELESTA") p1[term == tm & labels == lab, estimate]
  rng <- function(x) sprintf("%s-%s", f2(min(x)), f2(max(x)))
  p2e <- function(ctl, a, b) p2[control == ctl & cell_A == a & cell_B == b, estimate]
  qd_pub <- qd[labels == "published" & adjusted == TRUE & cell_A == "Tumour" & cell_B == "Treg"]
  brca_n <- p3[BRCA1 == 1, range(n)]
  sgn <- function(x) sprintf("%+.3f", x)
