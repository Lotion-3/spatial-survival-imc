  # ---- stage 2
  cacc <- fread(file.path(gen, "clq", "acceptance.csv"))
  lines <- c(lines, "## CLQ permutation null (stage 2)", "",
             md(cacc[, .(Run = run, k, Images = images, `Median permutation mean / k` = sprintf("%.4f", perm_mean_over_k_median),
                         `2.5-97.5%` = sprintf("%.3f-%.3f", perm_mean_over_k_q025, perm_mean_over_k_q975),
                         `Share flagged (lab rule)` = f3(share_flagged_lab_rule))]))

  # ---- hypotheses
  ho <- fread(file.path(mod, "hypothesis_outcomes.csv"))
  lines <- c(lines, "## Hypotheses and controls", "",
             md(ho[, .(ID = id, Test = test, Estimate = ifelse(is.na(lo), ifelse(is.na(estimate), "–", f3(estimate)), ci(estimate, lo, hi)),
                       p = fp(p), n = ifelse(is.na(n), "–", n), Outcome = outcome)]))
  p1 <- fread(file.path(mod, "p1_immune_fraction.csv"))
  lines <- c(lines, md(p1[, .(Cohort = cohort, Labels = labels, Contrast = sub("^(pam50|surrogate)", "", term),
                              `Immune-fraction difference` = ci(estimate, lo, hi), p = fp(p), n)]))
