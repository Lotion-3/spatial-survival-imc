                                              .SD), .SDcols = grep(" - LumA$", names(top), value = TRUE)]))
  tp <- q2t[adjusted == TRUE][order(p)][1:min(.N, 8)]
  lines <- c(lines, md(tp[, .(Pair = paste(cell_A, "->", cell_B), k, `TP53 mut - wt` = ci(estimate, lo, hi), p = fp(p),
