  lines <- c(lines, md(p2[, .(Control = control, Pair = paste(cell_A, "->", cell_B), `Basal - LumA` = ci(estimate, lo, hi),
                              p = fp(p), n)]))
  p3 <- fread(file.path(mod, "p3_brca1_descriptive.csv"))
  lines <- c(lines, md(p3[order(labels, cell_B, BRCA1), .(Labels = labels, Pair = paste(cell_A, "->", cell_B),
                                                          BRCA1 = ifelse(BRCA1 == 1, "mutant", "wild-type"), n,
                                                          `Mean CLQ` = f3(mean_clq), SD = f3(sd))]))
  qd <- fread(file.path(mod, "question_d_node_treg.csv"))
  lines <- c(lines, md(qd[, .(Labels = labels, Pair = paste(cell_A, "->", cell_B), Adjusted = ifelse(adjusted, "yes", "no"),
                              `Node-positive - negative` = ci(estimate, lo, hi), p = fp(p), n,
                              `n node+` = n_group1)]))

  # ---- Q1 / Q2 summaries
  q1 <- fread(file.path(mod, "q1_subtype_tests.csv"))
  q1c <- fread(file.path(mod, "q1_subtype_contrasts.csv"))
  q2t <- fread(file.path(mod, "q2_tp53.csv"))
  q2p <- fread(file.path(mod, "q2_pik3ca.csv"))
  fam <- rbind(
    q1[, .(Question = "Q1 subtype (F-test)", Adjusted = ifelse(adjusted, "composition-adjusted", "unadjusted"), Tests = .N,
           `q < 0.05` = sum(q < 0.05), `p < 0.05` = sum(p < 0.05)), by = adjusted][, -1],
    q2t[, .(Question = "Q2 TP53", Adjusted = ifelse(adjusted, "composition-adjusted", "unadjusted"), Tests = .N,
            `q < 0.05` = sum(q < 0.05), `p < 0.05` = sum(p < 0.05)), by = adjusted][, -1],
    q2p[, .(Question = "Q2 PIK3CA", Adjusted = ifelse(adjusted, "composition-adjusted", "unadjusted"), Tests = .N,
            `q < 0.05` = sum(q < 0.05), `p < 0.05` = sum(p < 0.05)), by = adjusted][, -1])
  lines <- c(lines, "## Association families (BH within each)", "", md(fam))
  top <- merge(q1[adjusted == TRUE & q < 0.05, .(k, cell_A, cell_B, F, q)],
               q1[adjusted == FALSE, .(k, cell_A, cell_B, q_unadj = q)], by = c("k", "cell_A", "cell_B"))
  top <- merge(top, dcast(q1c[adjusted == TRUE, .(k, cell_A, cell_B, contrast, e = sprintf("%+.2f", estimate))],
                          k + cell_A + cell_B ~ contrast, value.var = "e"), by = c("k", "cell_A", "cell_B"))
  setorder(top, q)
  if (nrow(top)) lines <- c(lines, md(top[, c(list(Pair = paste(cell_A, "->", cell_B), k = k, F = f2(F), q = fp(q),
